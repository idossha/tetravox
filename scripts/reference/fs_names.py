"""Generate packages/engine/src/scene/freesurfer-table.ts from FreeSurferColorLUT.txt, and check it against sources FreeSurfer did not write.

  fs_names.py generate <FreeSurferColorLUT.txt>
  fs_names.py check <MRtrix share/mrtrix3> [SimNIBS labeling_LUT.txt]   # prints agreement, exit 1 on a mismatch

MRtrix's fs_default.txt renumbers, so it is compared by name; SimNIBS's labeling_LUT.txt keeps FreeSurfer's ids.

The table is the aseg ids plus DK aparc (1000-1035, 2000-2035). Older tables say Left-Thalamus-Proper for 10 and 49:
the check maps that one spelling and reports it.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).parents[2] / "packages" / "engine" / "src" / "scene" / "freesurfer-table.ts"
ASEG = set(range(0, 86)) | {251, 252, 253, 254, 255}
DK = set(range(1000, 1036)) | set(range(2000, 2036))


def read_lut(path: Path) -> dict[int, tuple[str, list[int]]]:
    out = {}
    for raw in path.read_text(errors="replace").splitlines():
        line = raw.split("#")[0].strip()
        parts = line.split()
        if len(parts) >= 5 and parts[0].isdigit():
            out.setdefault(int(parts[0]), (parts[1], [int(c) for c in parts[2:5]]))
    return out


def embedded() -> dict[int, str]:
    return {int(i): n for i, n in re.findall(r"\[(\d+), '([^']+)',", OUT.read_text())}


def generate(lut: Path) -> None:
    table = read_lut(lut)
    rows = {i: n for i, n in sorted(table.items()) if i in ASEG | DK}
    body = "\n".join(f"  [{i}, '{n}', {c[0]}, {c[1]}, {c[2]}]," for i, (n, c) in rows.items())
    OUT.write_text(
        "// Generated by scripts/reference/fs_names.py from FreeSurfer's own colour table: aseg and DK aparc ids.\n"
        "export const FREESURFER_TABLE: readonly (readonly [number, string, number, number, number])[] = [\n"
        + body + "\n];\n"
    )
    print(f"{OUT}: {len(rows)} names from {lut}")


def check(share: Path, simnibs: Path | None) -> int:
    ours = embedded()
    bad = 0
    compared = 0
    def same(i: int, theirs: str, where: str) -> None:
        nonlocal bad, compared
        if i not in ours:
            return
        compared += 1
        a, b = ours[i].lower(), theirs.lower().replace("-proper", "")
        if a.replace("-proper", "") != b:
            bad += 1
            print(f"MISMATCH {i}: ours {ours[i]!r}, {where} {theirs!r}")
    # fs_default is `index short long r g b a`: long names, aseg and ctx.
    before = compared
    for raw in (share / "labelconvert/fs_default.txt").read_text().splitlines():
        parts = raw.split("#")[0].split()
        if len(parts) >= 3 and parts[0].isdigit():
            long = parts[2]
            match = [i for i, n in ours.items() if n.lower().replace("-proper", "") == long.lower().replace("-proper", "")]
            compared += 1
            if not match:
                bad += 1
                print(f"MISMATCH: MRtrix fs_default names {long!r}, which the table does not hold")
    print(f"labelconvert/fs_default.txt long names found in the table: {compared - before}")
    if simnibs is not None:
        before = compared
        for raw in simnibs.read_text().splitlines():
            parts = raw.split("#")[0].split()
            if len(parts) >= 2 and parts[0].isdigit():
                same(int(parts[0]), parts[1], "labeling_LUT")
        print(f"{simnibs.name}: compared {compared - before} (SimNIBS's own ids, informational where it renames)")
    print(f"{len(ours)} embedded names; {compared} comparisons; {bad} mismatches")
    return 1 if bad else 0


if __name__ == "__main__":
    if sys.argv[1] == "generate":
        generate(Path(sys.argv[2]))
    else:
        sys.exit(check(Path(sys.argv[2]), Path(sys.argv[3]) if len(sys.argv) > 3 else None))
